/// 知识卡的练习类型。
///
/// 卡片类型决定用户如何作答，以及系统如何判断本次练习是否通过。
enum CardType {
  /// 查看问题并主动回忆，翻面后由用户自行判断掌握程度。
  questionAnswer,

  /// 用户从多个选项中选择一个正确答案。
  singleChoice,

  /// 用户从多个选项中选择所有正确答案。
  multipleChoice,

  /// 用户录制口头回答，并通过回放或语音识别进行判断。
  voiceAnswer,

  /// 用户朗读目标文本，系统检查是否正确读出目标内容。
  pronunciation,

  /// 用户听取音频后，通过文字、选择或语音方式回答。
  listening,
}
